export default function PixelIcon({ type, className = "", label }) {
  const pixels = ICONS[type] || [];
  return (
    <svg
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : "true"}
      focusable="false"
    >
      {pixels.map(([x, y], i) => (
        <rect key={i} x={x} y={y} width="1" height="1" />
      ))}
    </svg>
  );
}
